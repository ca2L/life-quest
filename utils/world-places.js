// 按大洲分组，可按名称 / 国家 / 大洲 / 玩法标签过滤；返回带 icon 的分组数组。
function groupPlaces(keyword) {
  const kw = String(keyword || '').trim().toLowerCase()
  return CONTINENTS.map((c) => ({
    name: c.name,
    icon: c.icon,
    places: PLACES.filter((p) => p.continent === c.name && (
      !kw || p.name.toLowerCase().indexOf(kw) >= 0
        || p.country.toLowerCase().indexOf(kw) >= 0
        || p.tags.toLowerCase().indexOf(kw) >= 0
        || c.name.toLowerCase().indexOf(kw) >= 0
    )),
  })).filter((g) => g.places.length)
}

function findPlace(name) {
  return PLACES.find((p) => p.name === name) || null
}

