const CONTENTS = { cook: COOK, live: LIVE, skill: SKILL }

function contentOf(guideId) {
  return CONTENTS[guideId] || []
}

function countOf(guideId) {
  return contentOf(guideId).length
}

// 首页大卡上的内容预览（默认取前 3 个标题）
function previewOf(guideId, n) {
  return contentOf(guideId).slice(0, n || 3).map((x) => x.title)
}

/**
 * 今日 6 张专用：把一张「章节 / 菜名级」的推荐卡，确定性映射到该指南下的一篇可执行正文。
 *  - 用卡片序号 + 当日位次做取模，同一天同一张卡永远落到同一篇，不会每天乱跳；
 *  - 同一指南的两张卡加上位次偏移，尽量分散到不同篇，避免 6 张点开都是同一道菜。
 */
function contentByPick(guideId, no, index) {
  const list = contentOf(guideId)
  if (!list.length) return null
  const digits = String(no || '').replace(/\D/g, '')
  let n = parseInt(digits, 10)
  if (!Number.isFinite(n) || n <= 0) n = Number(index || 0) + 1
  const offset = Math.abs(Number(index) || 0) % list.length
  return list[(n - 1 + offset) % list.length]
}

module.exports = { CONTENTS, contentOf, countOf, previewOf, contentByPick }
